import assert from "node:assert/strict";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createServer } from "node:http2";
import type { AddressInfo } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { test } from "node:test";

import { create, fromBinary, toBinary, type DescMessage, type DescService, type Message } from "@bufbuild/protobuf";
import { timestampFromMs } from "@bufbuild/protobuf/wkt";
import { Code, ConnectError, createClient, type Transport } from "@connectrpc/connect";
import { connectNodeAdapter, createConnectTransport, createGrpcTransport } from "@connectrpc/connect-node";

import { SpecError } from "../../tools/generator/document.js";
import { generateProtos } from "../../tools/generator/grpc.js";
import { PlanError } from "../../tools/generator/plan.js";

const root = dirname(dirname(import.meta.dirname));
const protos = join(import.meta.dirname, "fixtures", "protos");
const label = "./tests/generator/fixtures/protos";

async function scratch(files: Readonly<Record<string, string>>): Promise<string> {
	const directory = await mkdtemp(join(tmpdir(), "dung-beetle-protos-"));
	for (const [name, source] of Object.entries(files)) {
		await mkdir(dirname(join(directory, name)), { recursive: true });
		await writeFile(join(directory, name), source, "utf8");
	}
	return directory;
}

test("the checked-in gRPC modules are what the generator writes today", async () => {
	const modules = await generateProtos(protos, label);

	assert.deepEqual(
		modules.map((module) => module.path),
		["common/v1/money_pb.ts", "widgets/v1/widgets_pb.ts"]
	);
	for (const module of modules) {
		const checked = (await readFile(join(root, "src", "grpc", ...module.path.split("/")), "utf8")).replaceAll("\r\n", "\n");
		assert.equal(checked, module.source, module.path);
	}
});

test("every generated file carries the banner that lets a re-run replace it", async () => {
	for (const module of await generateProtos(protos, label)) {
		assert.ok(module.source.startsWith(`// @generated by dung beetle from ${label} through protoc-gen-es. Do not edit.\n`));
	}
});

test("values and types are read from what protoc-gen-es exported", async () => {
	const widgets = (await generateProtos(protos, label)).find((module) => module.path.startsWith("widgets"));

	assert.deepEqual([...(widgets?.values ?? [])].sort(), [
		"GetWidgetRequestSchema",
		"ListWidgetsRequestSchema",
		"Size",
		"SizeSchema",
		"WidgetSchema",
		"WidgetService",
		"file_widgets_v1_widgets",
	]);
	assert.deepEqual([...(widgets?.types ?? [])].sort(), ["GetWidgetRequest", "ListWidgetsRequest", "Widget"]);
});

test("a path that is not a directory is refused", async () => {
	await assert.rejects(
		generateProtos(join(protos, "nope"), "./nope"),
		(error: unknown) => error instanceof SpecError && /\.\/nope is not a directory/u.test(error.message)
	);
});

test("a directory without .proto files is refused", async () => {
	const directory = await scratch({ "README.md": "nothing here\n" });
	try {
		await assert.rejects(generateProtos(directory, "./empty"), SpecError);
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});

test("a .proto file buf cannot compile is refused with buf's own message", async () => {
	const directory = await scratch({ "bad/v1/bad.proto": "syntax = \"proto3\";\npackage bad.v1;\nmessage A { Missing b = 1; }\n" });
	try {
		await assert.rejects(
			generateProtos(directory, "./bad"),
			(error: unknown) => error instanceof SpecError && /buf could not generate from \.\/bad/u.test(error.message) && /Missing/u.test(error.message)
		);
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});

test("two files exporting the same name are refused, naming both", async () => {
	const directory = await scratch({
		"a/v1/a.proto": "syntax = \"proto3\";\npackage a.v1;\nmessage Thing {}\n",
		"b/v1/b.proto": "syntax = \"proto3\";\npackage b.v1;\nmessage Thing {}\n",
	});
	try {
		await assert.rejects(
			generateProtos(directory, "./clash"),
			(error: unknown) =>
				error instanceof PlanError && /Thing is exported by both a\/v1\/a_pb\.ts and b\/v1\/b_pb\.ts/u.test(error.message)
		);
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});

test("the generator works from a copy of the protos in another directory", async () => {
	const directory = await mkdtemp(join(tmpdir(), "dung-beetle-protos-"));
	try {
		await cp(protos, directory, { recursive: true });
		const modules = await generateProtos(directory, label);

		assert.deepEqual(modules, await generateProtos(protos, label));
	} finally {
		await rm(directory, { recursive: true, force: true });
	}
});

/** What the tests below use from `widgets_pb.ts`, which is imported at run time. */
interface Widgets {
	readonly WidgetSchema: DescMessage;
	readonly WidgetService: DescService;
	readonly Size: { readonly UNSPECIFIED: number; readonly SMALL: number; readonly LARGE: number };
}

interface WidgetClient {
	getWidget(request: { id: string }): Promise<{ name: string }>;
	listWidgets(request: { size: number }): AsyncIterable<{ id: string }>;
}

/**
 * Generates the fixture protos into a directory inside `node_modules`, where
 * the generated imports of `@bufbuild/protobuf` resolve, and imports the
 * result. The round trip runs on what the generator writes now, not on the
 * checked-in copy, which a project that drops gRPC deletes.
 */
async function generatedWidgets(): Promise<{ widgets: Widgets; cleanup: () => Promise<void> }> {
	const cache = join(root, "node_modules", ".cache");
	await mkdir(cache, { recursive: true });
	const directory = await mkdtemp(join(cache, "dung-beetle-grpc-"));

	for (const module of await generateProtos(protos, label)) {
		const path = join(directory, ...module.path.split("/"));
		await mkdir(dirname(path), { recursive: true });
		await writeFile(path, module.source, "utf8");
	}

	const url = pathToFileURL(join(directory, "widgets", "v1", "widgets_pb.ts")).href;
	return {
		widgets: (await import(url)) as Widgets,
		cleanup: () => rm(directory, { recursive: true, force: true }),
	};
}

test("a message round-trips through the binary encoding", async () => {
	const { widgets, cleanup } = await generatedWidgets();
	try {
		const { WidgetSchema, Size } = widgets;
		const widget = create(WidgetSchema, {
			id: "w1",
			name: "sprocket",
			price: { currency: "EUR", minorUnits: 250n },
			createdAt: timestampFromMs(Date.UTC(2026, 10, 8)),
			size: Size.LARGE,
		} as never);

		assert.deepEqual(fromBinary(WidgetSchema, toBinary(WidgetSchema, widget)), widget);
	} finally {
		await cleanup();
	}
});

/** An HTTP/2 server for WidgetService, serving gRPC, gRPC-Web and Connect. */
async function serve({ WidgetSchema, WidgetService, Size }: Widgets): Promise<{ url: string; close: () => Promise<void> }> {
	type Widget = Message & { id: string; size: number };
	const stock = [
		create(WidgetSchema, { id: "w1", name: "small", size: Size.SMALL } as never),
		create(WidgetSchema, { id: "w2", name: "large", size: Size.LARGE } as never),
	] as Widget[];
	const implementation = {
		getWidget(request: { id: string }): Widget {
			const found = stock.find((widget) => widget.id === request.id);
			if (found === undefined) {
				throw new ConnectError(`no widget ${request.id}`, Code.NotFound);
			}
			return found;
		},
		async *listWidgets(request: { size: number }): AsyncGenerator<Widget> {
			yield* stock.filter((widget) => request.size === Size.UNSPECIFIED || widget.size === request.size);
		},
	};
	const server = createServer(
		connectNodeAdapter({
			routes: (router) => router.service(WidgetService, implementation as never),
		})
	);
	await new Promise<void>((resolve) => server.listen(0, "127.0.0.1", resolve));
	const { port } = server.address() as AddressInfo;

	return {
		url: `http://127.0.0.1:${port}`,
		close: () => new Promise((resolve) => server.close(() => resolve())),
	};
}

const transports: readonly [string, (url: string) => Transport][] = [
	["gRPC", (url) => createGrpcTransport({ baseUrl: url })],
	["Connect", (url) => createConnectTransport({ baseUrl: url, httpVersion: "2" })],
];

for (const [protocol, transport] of transports) {
	test(`the generated service is callable over ${protocol}, unary and server streaming`, async () => {
		const { widgets, cleanup } = await generatedWidgets();
		const server = await serve(widgets);
		try {
			const client = createClient(widgets.WidgetService, transport(server.url)) as unknown as WidgetClient;

			assert.equal((await client.getWidget({ id: "w2" })).name, "large");

			const streamed: string[] = [];
			for await (const widget of client.listWidgets({ size: widgets.Size.SMALL })) {
				streamed.push(widget.id);
			}
			assert.deepEqual(streamed, ["w1"]);

			await assert.rejects(
				client.getWidget({ id: "nope" }),
				(error: unknown) => error instanceof ConnectError && error.code === Code.NotFound
			);
		} finally {
			await server.close();
			await cleanup();
		}
	});
}
